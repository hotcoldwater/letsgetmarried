import assert from 'node:assert/strict';
import { accountRole, newToken, tokenValid, digest, passwordValid, hashPassword, verifyPassword } from '../lib/auth-core.mjs';
assert.equal(accountRole('integer0125'), 'groom');
assert.equal(accountRole(' HAWE123789 '), 'bride');
assert.equal(accountRole('someone-else'), null);
assert.equal(accountRole(null), null);
const token = newToken(); assert.equal(tokenValid(token), true);
assert.notEqual(newToken(), token); assert.equal(tokenValid('short'), false);
assert.equal(digest(token).length, 64); assert.notEqual(digest(token), token);
assert.equal(passwordValid('short'), false); assert.equal(passwordValid('x'.repeat(257)), false);
const password = 'a long private test phrase';
const hash = await hashPassword(password), another = await hashPassword(password);
assert.notEqual(hash, another); assert.equal(hash.includes(password), false);
assert.equal(await verifyPassword(password, hash), true);
assert.equal(await verifyPassword('a different test phrase', hash), false);
assert.equal(await verifyPassword(password, null), false);
assert.equal(await verifyPassword(password, 'corrupt'), false);
assert.equal(await verifyPassword(null, hash), false);
assert.equal(await verifyPassword('x'.repeat(257), hash), false);
console.log('19 username, password and session token checks passed');
